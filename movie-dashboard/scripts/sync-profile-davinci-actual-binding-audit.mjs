import {execFileSync} from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const dashboardRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(dashboardRoot, "..");
const motionStudioRoot = path.join(repoRoot, "motion-studio");
const auditPath = path.join(motionStudioRoot, "scripts/profile-v1-davinci-actual-binding-audit.mts");
const outputPath = path.join(dashboardRoot, "src/data/profileDavinciActualBindingAudit.generated.ts");

const audit = JSON.parse(execFileSync(process.execPath, ["--no-warnings", auditPath, "--json"], {
  cwd: motionStudioRoot,
  encoding: "utf8",
}));

if (audit.schemaVersion !== "profile-v1-davinci-actual-binding-audit/v1" || audit.authority !== "DERIVED_DAVINCI_ACTUAL_BINDING_AUDIT") {
  throw new Error(`Unexpected Profile DaVinci Actual binding audit: ${audit.schemaVersion}/${audit.authority}`);
}
if (audit.productionReady !== false) throw new Error("Profile DaVinci Actual binding audit must never promote production readiness");
if (audit.state === "CURRENT_PASS" && audit.actualEvidence?.allChecksPass !== true) throw new Error("CURRENT_PASS requires all Actual checks PASS");
if (audit.state === "NOT_RUN" && audit.actualEvidence?.exists) throw new Error("NOT_RUN cannot hide an existing Actual evidence file");
if (!audit.finalApproval || typeof audit.finalApproval.current !== "boolean") throw new Error("Profile audit must carry final approval binding state");
if (!audit.finalApproval.exists && audit.finalApproval.decision !== "NOT_RUN") throw new Error("Missing Profile final approval must remain NOT_RUN");

const output = `// AUTO-GENERATED by scripts/sync-profile-davinci-actual-binding-audit.mjs\n// Read-only audit of the recovery-bound Mac DaVinci Actual evidence and final approval. Do not edit by hand.\n\nexport const profileDavinciActualBindingAudit = ${JSON.stringify(audit, null, 2)} as const;\n`;

if (process.argv.includes("--write")) {
  fs.writeFileSync(outputPath, output, "utf8");
  console.log(`Profile DaVinci Actual binding audit synced: ${audit.state}, current=${audit.current}, approvalCurrent=${audit.finalApproval.current}, productionReady=${audit.productionReady}`);
  process.exit(0);
}
if (!fs.existsSync(outputPath)) {
  console.error("Profile DaVinci Actual binding audit generated file is missing. Run: node scripts/sync-profile-davinci-actual-binding-audit.mjs --write");
  process.exit(1);
}
if (fs.readFileSync(outputPath, "utf8") !== output) {
  console.error("Profile DaVinci Actual binding audit generated snapshot is stale. Run: node scripts/sync-profile-davinci-actual-binding-audit.mjs --write");
  process.exit(1);
}
console.log(`Profile DaVinci Actual binding audit current: ${audit.state}, bindingCurrent=${audit.current}, approvalCurrent=${audit.finalApproval.current}, productionReady=${audit.productionReady}`);
