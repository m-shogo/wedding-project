import {execFileSync} from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const dashboardRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(dashboardRoot, "..");
const motionStudioRoot = path.join(repoRoot, "motion-studio");
const statusScript = path.join(motionStudioRoot, "scripts/opening-v1-audio-listening-review.mts");
const outputPath = path.join(dashboardRoot, "src/data/openingAudioListeningStatus.generated.ts");

const raw = execFileSync(process.execPath, ["--no-warnings", statusScript, "--json"], {
  cwd: motionStudioRoot,
  encoding: "utf8",
});
const status = JSON.parse(raw);

if (status.schemaVersion !== "opening-v1-audio-listening-review-status/v1") {
  throw new Error(`Unexpected Opening audio review schema: ${status.schemaVersion ?? "missing"}`);
}
if (status.authority !== "DERIVED_OPENING_AUDIO_LISTENING_REVIEW_STATUS") {
  throw new Error(`Unexpected Opening audio review authority: ${status.authority ?? "missing"}`);
}
if (status.remotionStudioActual !== "NOT_RUN" || status.macDaVinciActual !== "NOT_RUN") {
  throw new Error("Opening audio review must not promote Studio/Mac GUI Actual");
}
if (status.productionReady !== false) {
  throw new Error("Opening audio review must not promote productionReady");
}

const snapshot = {
  ...status,
  recovery:
    status.state === "PASS"
      ? []
      : [
          "rights-cleared Opening previewを最後まで人間が再生",
          "node --no-warnings scripts/opening-v1-audio-listening-review.mts --init",
          "audibility / balance / startIntegrity / endIntegrity / pictureSync をHuman QA",
          "node --no-warnings scripts/opening-v1-audio-listening-review.mts --strict",
        ],
  guardrails: [
    "BGM_RIGHTS_CLEARED != HUMAN_AUDIO_LISTENING_PASS",
    "PREVIEW_OR_BGM_SHA_CHANGED => HUMAN_AUDIO_LISTENING_REVIEW_STALE",
    "HUMAN_AUDIO_LISTENING_PASS != REMOTION_STUDIO_ACTUAL_VERIFIED",
    "HUMAN_AUDIO_LISTENING_PASS != MAC_DAVINCI_ACTUAL_VERIFIED",
    "HUMAN_AUDIO_LISTENING_PASS != PRODUCTION_READY",
  ],
};

const output = `// AUTO-GENERATED by scripts/sync-opening-audio-listening-status.mjs\n// Motion Studio Human audio review status is the authority. Do not edit by hand.\n\nexport const openingAudioListeningStatus = ${JSON.stringify(snapshot, null, 2)} as const;\n`;

if (process.argv.includes("--write")) {
  fs.writeFileSync(outputPath, output, "utf8");
  console.log(`Opening audio listening status synced: ${snapshot.state}`);
  process.exit(0);
}

if (!fs.existsSync(outputPath)) {
  console.error("Opening audio listening generated file is missing. Run: node scripts/sync-opening-audio-listening-status.mjs --write");
  process.exit(1);
}
if (fs.readFileSync(outputPath, "utf8") !== output) {
  console.error("Opening audio listening generated snapshot is stale. Run: node scripts/sync-opening-audio-listening-status.mjs --write");
  process.exit(1);
}
console.log(`Opening audio listening status current: ${snapshot.state}, StudioActual=${snapshot.remotionStudioActual}, MacDaVinciActual=${snapshot.macDaVinciActual}, productionReady=${snapshot.productionReady}`);
