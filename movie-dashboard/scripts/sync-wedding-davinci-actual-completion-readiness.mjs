import {execFileSync} from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const dashboardRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(dashboardRoot, "..");
const motionStudioRoot = path.join(repoRoot, "motion-studio");
const readinessPath = path.join(motionStudioRoot, "scripts/wedding-davinci-delivery-readiness.mts");
const outputPath = path.join(dashboardRoot, "src/data/weddingDavinciActualCompletionReadiness.generated.ts");

const report = JSON.parse(execFileSync(process.execPath, ["--no-warnings", readinessPath, "--json"], {
  cwd: motionStudioRoot,
  encoding: "utf8",
}));

if (report.schemaVersion !== "wedding-davinci-delivery-readiness/v1" || report.authority !== "DERIVED_WEDDING_DAVINCI_DELIVERY_READINESS") {
  throw new Error("Unexpected Wedding DaVinci delivery readiness contract");
}

const project = (movieId) => {
  const gate = report[movieId]?.completionGate;
  if (!gate || !["CURRENT", "BLOCKED"].includes(gate.state)) throw new Error(`${movieId} completion gate contract missing`);
  if (gate.current !== (gate.state === "CURRENT")) throw new Error(`${movieId} completion gate current/state mismatch`);
  return {
    state: gate.state,
    current: gate.current,
    receiptPath: gate.receiptPath,
    receiptSha256: gate.receiptSha256,
    recoverySha256: gate.recoverySha256,
    finishingEvidenceSha256: gate.finishingEvidenceSha256,
    transitionEvidenceSha256: gate.transitionEvidenceSha256,
    transitionProofSha256: gate.transitionProofSha256,
    blocker: gate.blocker,
    writeCommand: `cd motion-studio && node --no-warnings scripts/wedding-davinci-actual-completion-receipt.mts --movie=${movieId} --write`,
    strictCommand: `cd motion-studio && node --no-warnings scripts/wedding-davinci-actual-completion-receipt.mts --movie=${movieId}`,
  };
};

const snapshot = {
  schemaVersion: "wedding-davinci-actual-completion-dashboard/v1",
  authority: "MOTION_STUDIO_DERIVED_DAVINCI_ACTUAL_COMPLETION_READINESS",
  generatedFrom: "motion-studio/scripts/wedding-davinci-delivery-readiness.mts --json",
  opening: project("opening"),
  profile: project("profile"),
  guardrails: [
    "RECEIPT_DERIVED_ONLY != LIVE_MAC_DAVINCI_GUI_ACTUAL",
    "CURRENT_REQUIRES_FINISHING_AND_TRANSITION_HUMAN_PASS_ON_SAME_RECOVERY_SHA",
    "FINISHING_OR_TRANSITION_EVIDENCE_SHA_CHANGED => COMPLETION_RECEIPT_STALE",
    "COMPLETION_RECEIPT_CURRENT_REQUIRED_BEFORE_FINAL_DELIVERY_READY",
  ],
};

const output = `// AUTO-GENERATED by scripts/sync-wedding-davinci-actual-completion-readiness.mjs\n// Read-only snapshot of the canonical DaVinci Actual completion receipt gate. Do not edit by hand.\n\nexport const weddingDavinciActualCompletionReadiness = ${JSON.stringify(snapshot, null, 2)} as const;\n`;

if (process.argv.includes("--write")) {
  fs.writeFileSync(outputPath, output, "utf8");
  console.log(`Wedding DaVinci Actual completion readiness synced: opening=${snapshot.opening.state} profile=${snapshot.profile.state}`);
  process.exit(0);
}

if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== output) {
  console.error("Wedding DaVinci Actual completion dashboard snapshot stale; run sync with --write");
  process.exit(1);
}
console.log(`Wedding DaVinci Actual completion readiness current: opening=${snapshot.opening.state} profile=${snapshot.profile.state}`);
