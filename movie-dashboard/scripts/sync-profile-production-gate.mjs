import {execFileSync} from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const dashboardRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(dashboardRoot, "..");
const preflightPath = path.join(repoRoot, "motion-studio/scripts/profile-v1-assembly-preflight.mts");
const outputPath = path.join(dashboardRoot, "src/data/profileProductionGate.generated.ts");

const report = JSON.parse(
  execFileSync(process.execPath, ["--no-warnings", preflightPath, "--json"], {
    cwd: path.join(repoRoot, "motion-studio"),
    encoding: "utf8",
  }),
);

if (report.schemaVersion !== "profile-v1-assembly-preflight/v1") {
  throw new Error(`Unexpected Profile V1 preflight schema: ${report.schemaVersion}`);
}

const snapshot = {
  source: {
    preflight: "motion-studio/scripts/profile-v1-assembly-preflight.mts",
    plan: "motion-studio/src/data/profileV1ProductionPlan.ts",
    chapterPlan: "01_profile-movie/chapter-plan.md",
    structureReview: "motion-studio/scripts/profile-v1-full-structure-review.mts",
    realMediaReview: "motion-studio/scripts/profile-v1-real-media-review.mts",
  },
  chapterCount: report.chapters.length,
  chapters: report.chapters.map((chapter) => ({
    chapterId: chapter.chapterId,
    order: chapter.order,
    title: chapter.title,
    role: chapter.role,
    editIntent: chapter.editIntent,
    requiredCount: chapter.requiredCount,
    readyCount: chapter.readyCount,
    ready: chapter.ready,
  })),
  expectedMediaCount: report.media.expectedCount,
  resolvedMediaCount: report.media.readyCount,
  mediaMissingCount: report.media.expectedCount - report.media.readyCount,
  mediaSlots: report.media.slots.map((slot) => ({
    id: slot.id,
    chapterId: slot.chapterId,
    label: slot.label,
    kind: slot.kind,
    canonicalStem: slot.canonicalStem,
    file: slot.file,
    ready: slot.ready,
  })),
  bgm: {
    assetId: report.audio.assetId,
    path: report.audio.path,
    fileExists: report.audio.fileExists,
    rightsState: report.audio.rightsState,
    ready: report.audio.ready,
  },
  structureReview: {
    state: report.structureReview.state,
    evidencePath: report.structureReview.evidencePath,
    boundPreviewSha256: report.structureReview.boundPreviewSha256,
    currentPreviewSha256: report.structureReview.currentPreviewSha256,
    reviewer: report.structureReview.reviewer,
    reviewedAt: report.structureReview.reviewedAt,
    blockers: report.structureReview.blockers,
    humanReviewComplete: report.structureReview.humanReviewComplete,
  },
  realMediaReview: {
    state: report.realMediaReview.state,
    humanReviewComplete: report.realMediaReview.humanReviewComplete,
    blockers: report.realMediaReview.blockers,
    mediaExpected: report.realMediaReview.mediaExpected,
    mediaReviewed: report.realMediaReview.mediaReviewed,
  },
  inputGatePass: report.readiness.finalRenderEligible,
  blockingGatePass: report.readiness.assemblyReady,
  qa: {
    structurePreview: report.readiness.structurePreviewQaState,
    preview: report.readiness.previewQaState,
    humanContent: report.readiness.humanContentQaState,
    audio: report.readiness.audioQaState,
    macDaVinciActual: report.readiness.macDaVinciActualState,
  },
  productionReady: report.readiness.productionReady,
  nextActions: report.nextActions,
};

const output = `// AUTO-GENERATED by scripts/sync-profile-production-gate.mjs\n// Source of truth remains in motion-studio + 01_profile-movie/chapter-plan.md. Do not edit by hand.\n\nexport const profileProductionGate = ${JSON.stringify(snapshot, null, 2)} as const;\n`;

if (process.argv.includes("--write")) {
  fs.writeFileSync(outputPath, output, "utf8");
  console.log(`Profile production gate synced: ${snapshot.resolvedMediaCount}/${snapshot.expectedMediaCount} media, BGM=${snapshot.bgm.rightsState}, structure=${snapshot.structureReview.state}, realMediaQA=${snapshot.realMediaReview.state}`);
  process.exit(0);
}

if (!fs.existsSync(outputPath)) {
  console.error("Profile production gate generated file is missing. Run: node scripts/sync-profile-production-gate.mjs --write");
  process.exit(1);
}

const current = fs.readFileSync(outputPath, "utf8");
if (current !== output) {
  console.error("Profile production gate is stale. Run: node scripts/sync-profile-production-gate.mjs --write");
  console.error(`Current source state: ${snapshot.resolvedMediaCount}/${snapshot.expectedMediaCount} media, BGM=${snapshot.bgm.rightsState}, structure=${snapshot.structureReview.state}, realMediaQA=${snapshot.realMediaReview.state}`);
  process.exit(1);
}

console.log(`Profile production gate current: ${snapshot.resolvedMediaCount}/${snapshot.expectedMediaCount} media, BGM=${snapshot.bgm.rightsState}, structure=${snapshot.structureReview.state}, realMediaQA=${snapshot.realMediaReview.state}, blocked=${!snapshot.blockingGatePass}`);
