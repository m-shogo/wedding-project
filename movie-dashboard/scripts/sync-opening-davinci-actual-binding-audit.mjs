import {execFileSync} from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const dashboardRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(dashboardRoot, "..");
const motionStudioRoot = path.join(repoRoot, "motion-studio");
const auditPath = path.join(motionStudioRoot, "scripts/opening-v1-davinci-actual-binding-audit.mts");
const outputPath = path.join(dashboardRoot, "src/data/openingDavinciActualBindingAudit.generated.ts");

const audit = JSON.parse(execFileSync(process.execPath, ["--no-warnings", auditPath, "--json"], {cwd: motionStudioRoot, encoding: "utf8"}));
if (audit.schemaVersion !== "opening-v1-davinci-actual-binding-audit/v1" || audit.authority !== "DERIVED_DAVINCI_ACTUAL_BINDING_AUDIT") throw new Error("Unexpected Opening DaVinci Actual binding audit contract");
if (audit.productionReady !== false) throw new Error("Opening audit must never promote production readiness");
if (audit.state === "CURRENT_PASS" && audit.actualEvidence?.allChecksPass !== true) throw new Error("CURRENT_PASS requires all Actual checks PASS");
if (audit.state === "NOT_RUN" && audit.actualEvidence?.exists) throw new Error("NOT_RUN cannot hide an existing Actual evidence file");

const output = `// AUTO-GENERATED by scripts/sync-opening-davinci-actual-binding-audit.mjs\n// Read-only audit of Opening recovery-bound Mac DaVinci Actual/final approval. Do not edit by hand.\n\nexport const openingDavinciActualBindingAudit = ${JSON.stringify(audit, null, 2)} as const;\n`;
if (process.argv.includes("--write")) { fs.writeFileSync(outputPath, output, "utf8"); console.log(`Opening DaVinci Actual audit synced: ${audit.state}`); process.exit(0); }
if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== output) { console.error("Opening DaVinci Actual audit snapshot stale; run sync with --write"); process.exit(1); }
console.log(`Opening DaVinci Actual audit current: ${audit.state}`);
