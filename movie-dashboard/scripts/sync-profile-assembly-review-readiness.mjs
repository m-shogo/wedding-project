import {execFileSync} from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const dashboardRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(dashboardRoot, "..");
const motionStudioRoot = path.join(repoRoot, "motion-studio");
const scriptPath = path.join(motionStudioRoot, "scripts/profile-v1-assembly-preflight.mts");
const outputPath = path.join(dashboardRoot, "src/data/profileAssemblyReviewReadiness.generated.ts");

const report = JSON.parse(
  execFileSync(process.execPath, ["--no-warnings", scriptPath, "--json"], {
    cwd: motionStudioRoot,
    encoding: "utf8",
  }),
);

if (report.schemaVersion !== "profile-v1-assembly-preflight/v1" || report.authority !== "MOTION_STUDIO_DERIVED_PREFLIGHT") {
  throw new Error(`Unexpected Profile assembly preflight contract: ${report.schemaVersion}/${report.authority}`);
}

const reviewSnapshot = (review) => ({
  state: String(review?.state ?? "NOT_RUN"),
  humanReviewComplete: Boolean(review?.humanReviewComplete ?? review?.humanAudioQaComplete ?? false),
  evidencePath: String(review?.evidencePath ?? ""),
  blockers: Array.isArray(review?.blockers) ? review.blockers.map(String) : [],
});

const snapshot = {
  source: "motion-studio/scripts/profile-v1-assembly-preflight.mts",
  finalRenderEligible: report.readiness?.finalRenderEligible === true,
  assemblyReady: report.readiness?.assemblyReady === true,
  structureReview: reviewSnapshot(report.structureReview),
  realMediaReview: {
    ...reviewSnapshot(report.realMediaReview),
    reviewedCount: Number(report.realMediaReview?.mediaReviewed ?? 0),
    expectedCount: Number(report.realMediaReview?.mediaExpected ?? 17),
  },
  audioReview: reviewSnapshot(report.audioReview),
  guardrails: [
    "FINAL_RENDER_ELIGIBLE != HUMAN_QA_COMPLETE",
    "STRUCTURE_REVIEW_PASS != REAL_MEDIA_REVIEW_PASS",
    "REAL_MEDIA_REVIEW_PASS != AUDIO_REVIEW_PASS",
    "DASHBOARD_STATUS != GUI_ACTUAL_EVIDENCE",
  ],
};

const output = `// AUTO-GENERATED by scripts/sync-profile-assembly-review-readiness.mjs\n// Motion Studio Profile assembly preflight is the authority. Do not edit by hand.\n\nexport const profileAssemblyReviewReadiness = ${JSON.stringify(snapshot, null, 2)} as const;\n`;

if (process.argv.includes("--write")) {
  fs.writeFileSync(outputPath, output, "utf8");
  console.log(`Profile assembly review readiness synced: eligible=${snapshot.finalRenderEligible}, structure=${snapshot.structureReview.state}, realMedia=${snapshot.realMediaReview.state}, audio=${snapshot.audioReview.state}, assemblyReady=${snapshot.assemblyReady}`);
  process.exit(0);
}

if (!fs.existsSync(outputPath)) {
  console.error("Profile assembly review readiness generated file is missing. Run: node scripts/sync-profile-assembly-review-readiness.mjs --write");
  process.exit(1);
}
if (fs.readFileSync(outputPath, "utf8") !== output) {
  console.error("Profile assembly review readiness snapshot is stale. Run: node scripts/sync-profile-assembly-review-readiness.mjs --write");
  process.exit(1);
}
console.log(`Profile assembly review readiness current: eligible=${snapshot.finalRenderEligible}, structure=${snapshot.structureReview.state}, realMedia=${snapshot.realMediaReview.state}, audio=${snapshot.audioReview.state}, assemblyReady=${snapshot.assemblyReady}`);
