import {spawnSync} from 'node:child_process';
import {writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const dashboardRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));
const motionRoot = resolve(dashboardRoot, '..', 'motion-studio');
const target = resolve(dashboardRoot, 'src/data/weddingFinalDeliveryEvidenceManifestReadiness.generated.ts');
const command = 'node --no-warnings scripts/wedding-final-delivery-evidence-manifest-currentness.mts --json';
const run = spawnSync(process.execPath, ['--no-warnings', 'scripts/wedding-final-delivery-evidence-manifest-currentness.mts', '--json'], {cwd: motionRoot, encoding: 'utf8'});
if (run.status !== 0) throw new Error(run.stderr || run.stdout || 'Final delivery evidence manifest currentness failed');
const currentness = JSON.parse(run.stdout);
const payload = {
  schemaVersion: 'wedding-final-delivery-evidence-manifest-dashboard/v1',
  authority: 'MOTION_STUDIO_DERIVED_FINAL_DELIVERY_EVIDENCE_MANIFEST_READINESS',
  generatedFrom: command,
  state: currentness.state,
  current: currentness.current,
  manifestPath: currentness.manifestPath,
  mismatches: currentness.mismatches ?? [],
  manifestSha256: currentness.carried?.manifestSha256 ?? null,
  readinessSha256: currentness.carried?.readinessSha256 ?? null,
  openingEvidenceChainSha256: currentness.carried?.openingEvidenceChainSha256 ?? null,
  profileEvidenceChainSha256: currentness.carried?.profileEvidenceChainSha256 ?? null,
  writeCommand: 'cd motion-studio && node --no-warnings scripts/wedding-final-delivery-evidence-manifest.mts --write',
  strictCommand: 'cd motion-studio && node --no-warnings scripts/wedding-final-delivery-evidence-manifest-currentness.mts --strict-current',
  guardrails: [
    'GENERATED_DASHBOARD_SNAPSHOT != LIVE_MAC_DAVINCI_GUI_ACTUAL',
    'CURRENT_REQUIRES_CANONICAL_CLI_STRICT_CURRENT',
    'MISSING_MANIFEST => NOT_RUN',
    'ANY_BOUND_SHA_DRIFT => STALE',
    'HUMAN_FINAL_APPROVAL_NOT_PROMOTED_BY_DASHBOARD',
  ],
};
writeFileSync(target, `// AUTO-GENERATED by scripts/sync-wedding-final-delivery-evidence-manifest-readiness.mjs\n// Read-only snapshot. Canonical currentness remains the Motion Studio CLI strict verifier.\n\nexport const weddingFinalDeliveryEvidenceManifestReadiness = ${JSON.stringify(payload, null, 2)} as const;\n`);
console.log(`Synced final delivery evidence manifest dashboard snapshot: ${payload.state}`);
