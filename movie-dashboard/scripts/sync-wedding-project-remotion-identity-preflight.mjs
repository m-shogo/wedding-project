import {execFileSync} from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const dashboardRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(dashboardRoot, "..");
const motionStudioRoot = path.join(repoRoot, "motion-studio");
const sessionPlanPath = path.join(motionStudioRoot, "scripts/wedding-davinci-actual-session-plan.mts");
const outputPath = path.join(dashboardRoot, "src/data/weddingProjectRemotionIdentityPreflight.generated.ts");

const report = JSON.parse(execFileSync(process.execPath, ["--no-warnings", sessionPlanPath, "--json"], {
  cwd: motionStudioRoot,
  encoding: "utf8",
}));

if (report.schemaVersion !== "wedding-davinci-actual-session-plan/v1") throw new Error("Unexpected Wedding DaVinci session-plan schema");
if (report.authority !== "DERIVED_MAC_DAVINCI_ACTUAL_SESSION_PLAN") throw new Error("Unexpected Wedding DaVinci session-plan authority");

const normalize = (movie) => {
  const value = report?.projects?.[movie]?.projectRemotionIdentityPreflight;
  if (!value || !["CURRENT", "NOT_APPLICABLE", "INVALID"].includes(value.state)) {
    throw new Error(`${movie} Project Remotion identity preflight state missing`);
  }
  const exactCommand = `node --no-warnings scripts/verify-wedding-production-handoff-provenance.mts --movie=${movie}`;
  if (value.command !== exactCommand) throw new Error(`${movie} Project Remotion identity verifier command drift`);
  if (value.state === "CURRENT" && (!value.current || !value.applicable || value.error !== null)) {
    throw new Error(`${movie} CURRENT Project Remotion identity preflight is inconsistent`);
  }
  if (value.state === "NOT_APPLICABLE" && (value.current || value.applicable || value.error !== null)) {
    throw new Error(`${movie} NOT_APPLICABLE Project Remotion identity preflight is inconsistent`);
  }
  if (value.state === "INVALID" && (value.current || !value.applicable || !value.error)) {
    throw new Error(`${movie} INVALID Project Remotion identity preflight must fail closed`);
  }
  return {
    state: value.state,
    current: value.current,
    applicable: value.applicable,
    command: value.command,
    resolveSidecarSha256: value.resolveSidecarSha256 ?? null,
    receiptSha256: value.receiptSha256 ?? null,
    sourceBatchSha256: value.sourceBatchSha256 ?? null,
    error: value.error,
  };
};

const snapshot = {
  schemaVersion: "wedding-project-remotion-identity-dashboard-preflight/v1",
  authority: "MOTION_STUDIO_DERIVED_PROJECT_REMOTION_IDENTITY_PREFLIGHT",
  opening: normalize("opening"),
  profile: normalize("profile"),
  guardrails: [
    "GENERATED_DASHBOARD_SNAPSHOT != LIVE_MAC_GUI_ACTUAL",
    "PROJECT_REMOTION_IDENTITY_CURRENT_REQUIRES_CANONICAL_PRODUCTION_HANDOFF_VERIFIER_PASS",
    "PROJECT_REMOTION_IDENTITY_INVALID => GUI_ACTUAL_START_BLOCKED",
    "PROJECT_REMOTION_IDENTITY_NOT_APPLICABLE != VERIFIED",
    "CI_MUST_NOT_PROMOTE_MAC_GUI_ACTUAL",
  ],
};

const output = `// AUTO-GENERATED by scripts/sync-wedding-project-remotion-identity-preflight.mjs\n// Motion Studio Project Remotion identity preflight for Motion Zukan display. Do not edit by hand.\n\nexport const weddingProjectRemotionIdentityPreflight = ${JSON.stringify(snapshot, null, 2)} as const;\n`;

if (process.argv.includes("--write")) {
  fs.writeFileSync(outputPath, output, "utf8");
  console.log(`Wedding Project Remotion identity dashboard preflight synced: Opening=${snapshot.opening.state} Profile=${snapshot.profile.state}`);
  process.exit(0);
}

if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== output) {
  console.error("Wedding Project Remotion identity dashboard preflight snapshot stale; run sync with --write");
  process.exit(1);
}

console.log(`Wedding Project Remotion identity dashboard preflight current: Opening=${snapshot.opening.state} Profile=${snapshot.profile.state}`);
