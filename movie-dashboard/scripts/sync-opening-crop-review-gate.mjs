import {createHash} from "node:crypto";
import {execFileSync} from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const dashboardRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(dashboardRoot, "..");
const reviewScript = path.join(repoRoot, "motion-studio/scripts/opening-v1-crop-review-evidence.mts");
const evidenceRelativePath = "motion-studio/out/qa/opening-v1-crop-review-evidence.json";
const evidencePath = path.join(repoRoot, evidenceRelativePath);
const outputPath = path.join(dashboardRoot, "src/data/openingCropReviewGate.generated.ts");
const sha256 = (value) => createHash("sha256").update(value).digest("hex");

const status = JSON.parse(
  execFileSync(process.execPath, ["--no-warnings", reviewScript, "--json"], {
    cwd: path.join(repoRoot, "motion-studio"),
    encoding: "utf8",
  }),
);

if (
  status.schemaVersion !== "opening-v1-crop-review-status/v1" ||
  status.authority !== "DERIVED_OPENING_CROP_REVIEW_STATUS"
) {
  throw new Error(`Unexpected Opening crop review status: ${status.schemaVersion}/${status.authority}`);
}

function emptyAudit(parseState = "MISSING", evidenceSha256 = null) {
  return {
    evidencePath: evidenceRelativePath,
    evidenceExists: parseState !== "MISSING",
    evidenceSha256,
    parseState,
    boundAt: null,
    bindingFingerprintSha256: null,
    slots: [],
    overall: "NOT_RUN",
    macStudioActual: "NOT_RUN",
    macDaVinciActual: "NOT_RUN",
    productionReady: false,
  };
}

function buildAudit() {
  if (!fs.existsSync(evidencePath)) return emptyAudit();
  const raw = fs.readFileSync(evidencePath);
  const evidenceSha256 = sha256(raw);
  let evidence;
  try {
    evidence = JSON.parse(raw.toString("utf8"));
  } catch {
    return emptyAudit("INVALID_JSON", evidenceSha256);
  }

  const slots = Array.isArray(evidence?.slots)
    ? evidence.slots.map((slot) => ({
        key: typeof slot?.key === "string" ? slot.key : null,
        file: typeof slot?.file === "string" ? slot.file : null,
        mediaSha256: typeof slot?.mediaSha256 === "string" ? slot.mediaSha256 : null,
        focus: slot?.focus && typeof slot.focus === "object"
          ? {x: Number(slot.focus.x), y: Number(slot.focus.y)}
          : null,
        fit: typeof slot?.fit === "string" ? slot.fit : null,
        focusSource: typeof slot?.focusSource === "string" ? slot.focusSource : null,
        fitSource: typeof slot?.fitSource === "string" ? slot.fitSource : null,
        cropQaRequired: Boolean(slot?.cropQaRequired),
        presentationRevision: typeof slot?.presentationRevision === "string" ? slot.presentationRevision : null,
        review: slot?.review ?? "NOT_RUN",
        reviewer: typeof slot?.reviewer === "string" ? slot.reviewer : null,
        reviewedAt: typeof slot?.reviewedAt === "string" ? slot.reviewedAt : null,
        notes: typeof slot?.notes === "string" ? slot.notes : "",
      }))
    : [];

  return {
    evidencePath: evidenceRelativePath,
    evidenceExists: true,
    evidenceSha256,
    parseState: "PARSED",
    boundAt: typeof evidence?.boundAt === "string" ? evidence.boundAt : null,
    bindingFingerprintSha256:
      typeof evidence?.bindingFingerprintSha256 === "string" ? evidence.bindingFingerprintSha256 : null,
    slots,
    overall: evidence?.overall ?? "NOT_RUN",
    macStudioActual: evidence?.macStudioActual ?? "NOT_RUN",
    macDaVinciActual: evidence?.macDaVinciActual ?? "NOT_RUN",
    productionReady: evidence?.productionReady === true,
  };
}

const snapshot = {
  source: "motion-studio/scripts/opening-v1-crop-review-evidence.mts",
  state: status.state,
  blockers: status.blockers,
  reviewedCount: status.reviewedCount,
  requiredCount: status.requiredCount,
  macStudioActual: status.macStudioActual,
  macDaVinciActual: status.macDaVinciActual,
  productionReady: status.productionReady,
  audit: buildAudit(),
};

const output = `// AUTO-GENERATED by scripts/sync-opening-crop-review-gate.mjs\n// Human evidence lives under motion-studio/out and is never manufactured by this file.\n\nexport const openingCropReviewGate = ${JSON.stringify(snapshot, null, 2)} as const;\n`;

if (process.argv.includes("--write")) {
  fs.writeFileSync(outputPath, output, "utf8");
  console.log(`Opening crop review gate synced: ${snapshot.state} ${snapshot.reviewedCount}/${snapshot.requiredCount}`);
  process.exit(0);
}

if (!fs.existsSync(outputPath)) {
  console.error("Opening crop review generated gate is missing. Run: node scripts/sync-opening-crop-review-gate.mjs --write");
  process.exit(1);
}

const current = fs.readFileSync(outputPath, "utf8");
if (current !== output) {
  console.error("Opening crop review generated gate is stale. Run: node scripts/sync-opening-crop-review-gate.mjs --write");
  process.exit(1);
}

console.log(`Opening crop review gate current: ${snapshot.state} ${snapshot.reviewedCount}/${snapshot.requiredCount}`);
