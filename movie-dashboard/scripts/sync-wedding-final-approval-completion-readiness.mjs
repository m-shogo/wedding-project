import {execFileSync} from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const dashboardRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(dashboardRoot, "..");
const motionStudioRoot = path.join(repoRoot, "motion-studio");
const readinessPath = path.join(motionStudioRoot, "scripts/wedding-davinci-delivery-readiness.mts");
const outputPath = path.join(dashboardRoot, "src/data/weddingFinalApprovalCompletionReadiness.generated.ts");

const report = JSON.parse(execFileSync(process.execPath, ["--no-warnings", readinessPath, "--json"], {cwd: motionStudioRoot, encoding: "utf8"}));
if (report.schemaVersion !== "wedding-davinci-delivery-readiness/v1" || report.authority !== "DERIVED_WEDDING_DAVINCI_DELIVERY_READINESS") throw new Error("Unexpected Wedding DaVinci delivery readiness contract");

const project = (movieId) => {
  const gate = report[movieId]?.approvalCompletionGate;
  if (!gate || !["CURRENT", "BLOCKED"].includes(gate.state)) throw new Error(`${movieId} final approval completion gate contract missing`);
  if (gate.current !== (gate.state === "CURRENT")) throw new Error(`${movieId} final approval completion current/state mismatch`);
  return {
    state: gate.state,
    current: gate.current,
    bindingPath: gate.bindingPath,
    bindingSha256: gate.bindingSha256,
    finalApprovalSha256: gate.finalApprovalSha256,
    completionReceiptSha256: gate.completionReceiptSha256,
    transitionProofSha256: gate.transitionProofSha256,
    recoverySha256: gate.recoverySha256,
    finishingEvidenceSha256: gate.finishingEvidenceSha256,
    writeCommand: `cd motion-studio && node --no-warnings scripts/wedding-final-approval-completion-binding.mts --movie=${movieId} --write`,
    strictCommand: `cd motion-studio && node --no-warnings scripts/wedding-final-approval-completion-binding.mts --movie=${movieId}`,
  };
};

const snapshot = {
  schemaVersion: "wedding-final-approval-completion-dashboard/v1",
  authority: "MOTION_STUDIO_DERIVED_FINAL_APPROVAL_COMPLETION_READINESS",
  generatedFrom: "motion-studio/scripts/wedding-davinci-delivery-readiness.mts --json",
  opening: project("opening"),
  profile: project("profile"),
  guardrails: [
    "DERIVED_BINDING != HUMAN_FINAL_APPROVAL",
    "DERIVED_BINDING != LIVE_MAC_DAVINCI_GUI_ACTUAL",
    "CURRENT_REQUIRES_HUMAN_FINAL_APPROVAL_AND_ACTUAL_COMPLETION_ON_SAME_RECOVERY",
    "FINAL_APPROVAL_OR_COMPLETION_RECEIPT_SHA_CHANGED => BINDING_STALE",
  ],
};

const output = `// AUTO-GENERATED by scripts/sync-wedding-final-approval-completion-readiness.mjs\n// Read-only snapshot of the canonical final approval completion binding gate. Do not edit by hand.\n\nexport const weddingFinalApprovalCompletionReadiness = ${JSON.stringify(snapshot, null, 2)} as const;\n`;
if (process.argv.includes("--write")) {
  fs.writeFileSync(outputPath, output, "utf8");
  console.log(`Wedding final approval completion readiness synced: opening=${snapshot.opening.state} profile=${snapshot.profile.state}`);
  process.exit(0);
}
if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== output) {
  console.error("Wedding final approval completion dashboard snapshot stale; run sync with --write");
  process.exit(1);
}
console.log(`Wedding final approval completion readiness current: opening=${snapshot.opening.state} profile=${snapshot.profile.state}`);
