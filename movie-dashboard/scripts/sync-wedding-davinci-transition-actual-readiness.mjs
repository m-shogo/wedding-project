import {execFileSync} from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const dashboardRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(dashboardRoot, "..");
const motionStudioRoot = path.join(repoRoot, "motion-studio");
const readinessPath = path.join(motionStudioRoot, "scripts/wedding-davinci-delivery-readiness.mts");
const outputPath = path.join(dashboardRoot, "src/data/weddingDavinciTransitionActualReadiness.generated.ts");

const report = JSON.parse(execFileSync(process.execPath, ["--no-warnings", readinessPath, "--json"], {
  cwd: motionStudioRoot,
  encoding: "utf8",
}));

if (report.schemaVersion !== "wedding-davinci-delivery-readiness/v1" || report.authority !== "DERIVED_WEDDING_DAVINCI_DELIVERY_READINESS") {
  throw new Error("Unexpected Wedding DaVinci delivery readiness contract");
}

const project = (movieId) => {
  const entry = report[movieId];
  if (!entry?.transitionGate || !["CURRENT", "BLOCKED"].includes(entry.transitionGate.state)) {
    throw new Error(`${movieId} transition gate contract missing`);
  }
  if (entry.transitionGate.current !== (entry.transitionGate.state === "CURRENT")) {
    throw new Error(`${movieId} transition gate current/state mismatch`);
  }
  return {
    state: entry.transitionGate.state,
    current: entry.transitionGate.current,
    evidencePath: entry.transitionGate.evidencePath,
    evidenceSha256: entry.transitionActualEvidenceSha256,
    transitionProofSha256: entry.transitionProofSha256,
    edgeCount: entry.transitionGate.edgeCount,
    crossDissolveCount: entry.transitionGate.crossDissolveCount,
    reviewOverall: entry.transitionGate.reviewOverall,
    initCommand: `cd motion-studio && node --no-warnings scripts/wedding-davinci-transition-actual-evidence.mts --movie=${movieId} --init`,
    strictCommand: `cd motion-studio && node --no-warnings scripts/wedding-davinci-transition-actual-evidence.mts --movie=${movieId} --strict`,
    finalGateCommand: `cd motion-studio && node --no-warnings scripts/wedding-final-delivery-transition-gate.mts --movie=${movieId}`,
  };
};

const snapshot = {
  schemaVersion: "wedding-davinci-transition-actual-dashboard/v1",
  authority: "MOTION_STUDIO_DERIVED_TRANSITION_ACTUAL_READINESS",
  generatedFrom: "motion-studio/scripts/wedding-davinci-delivery-readiness.mts --json",
  opening: project("opening"),
  profile: project("profile"),
  guardrails: [
    "GENERATED_DASHBOARD_SNAPSHOT != LIVE_MAC_DAVINCI_GUI_ACTUAL",
    "NOT_RUN != PASS",
    "CURRENT_REQUIRES_CANONICAL_CLI_STRICT",
    "EVIDENCE_OR_TRANSITION_PROOF_SHA_CHANGED => DASHBOARD_SNAPSHOT_STALE",
  ],
};

const output = `// AUTO-GENERATED by scripts/sync-wedding-davinci-transition-actual-readiness.mjs\n// Read-only snapshot of the canonical transition Actual delivery gate. Do not edit by hand.\n\nexport const weddingDavinciTransitionActualReadiness = ${JSON.stringify(snapshot, null, 2)} as const;\n`;

if (process.argv.includes("--write")) {
  fs.writeFileSync(outputPath, output, "utf8");
  console.log(`Wedding DaVinci transition Actual readiness synced: opening=${snapshot.opening.state} profile=${snapshot.profile.state}`);
  process.exit(0);
}

if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== output) {
  console.error("Wedding DaVinci transition Actual dashboard snapshot stale; run sync with --write");
  process.exit(1);
}
console.log(`Wedding DaVinci transition Actual readiness current: opening=${snapshot.opening.state} profile=${snapshot.profile.state}`);