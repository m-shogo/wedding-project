import {execFileSync} from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const dashboardRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(dashboardRoot, "..");
const motionStudioRoot = path.join(repoRoot, "motion-studio");
const readinessPath = path.join(motionStudioRoot, "scripts/wedding-davinci-delivery-readiness.mts");
const outputPath = path.join(dashboardRoot, "src/data/weddingProjectMotionProvenancePreflight.generated.ts");

const report = JSON.parse(execFileSync(process.execPath, ["--no-warnings", readinessPath, "--json"], {
  cwd: motionStudioRoot,
  encoding: "utf8",
}));

if (report.schemaVersion !== "wedding-davinci-delivery-readiness/v1") throw new Error("Unexpected Wedding DaVinci readiness schema");
if (report.authority !== "DERIVED_WEDDING_DAVINCI_DELIVERY_READINESS") throw new Error("Unexpected Wedding DaVinci readiness authority");

const normalize = (movie) => {
  const value = report?.[movie]?.projectMotion;
  if (!value || !["CURRENT", "NOT_APPLICABLE", "INVALID"].includes(value.state)) {
    throw new Error(`${movie} Project Motion provenance state missing`);
  }
  const exactCommand = `node --no-warnings scripts/verify-wedding-project-motion-production-provenance.mts --movie=${movie}`;
  if (value.command !== exactCommand) throw new Error(`${movie} Project Motion verifier command drift`);
  if (value.state === "CURRENT" && (!value.current || !value.applicable || value.error !== null)) {
    throw new Error(`${movie} CURRENT Project Motion preflight is inconsistent`);
  }
  if (value.state === "NOT_APPLICABLE" && (value.current || value.applicable || value.error !== null)) {
    throw new Error(`${movie} NOT_APPLICABLE Project Motion preflight is inconsistent`);
  }
  if (value.state === "INVALID" && (value.current || !value.applicable || !value.error)) {
    throw new Error(`${movie} INVALID Project Motion preflight must fail closed`);
  }
  return {
    state: value.state,
    current: value.current,
    applicable: value.applicable,
    command: value.command,
    error: value.error,
  };
};

const snapshot = {
  schemaVersion: "wedding-project-motion-dashboard-preflight/v1",
  authority: "MOTION_STUDIO_DERIVED_PROJECT_MOTION_PROVENANCE_PREFLIGHT",
  opening: normalize("opening"),
  profile: normalize("profile"),
  guardrails: [
    "GENERATED_DASHBOARD_SNAPSHOT != LIVE_MAC_GUI_ACTUAL",
    "PROJECT_MOTION_CURRENT_REQUIRES_CANONICAL_PROVENANCE_VERIFIER_PASS",
    "PROJECT_MOTION_INVALID => FINAL_DELIVERY_BLOCKED",
    "NOT_APPLICABLE != VERIFIED",
    "CI_MUST_NOT_PROMOTE_MAC_GUI_ACTUAL",
  ],
};

const output = `// AUTO-GENERATED by scripts/sync-wedding-project-motion-provenance-preflight.mjs\n// Motion Studio Project Motion provenance preflight for Motion Zukan display. Do not edit by hand.\n\nexport const weddingProjectMotionProvenancePreflight = ${JSON.stringify(snapshot, null, 2)} as const;\n`;

if (process.argv.includes("--write")) {
  fs.writeFileSync(outputPath, output, "utf8");
  console.log(`Wedding Project Motion dashboard preflight synced: Opening=${snapshot.opening.state} Profile=${snapshot.profile.state}`);
  process.exit(0);
}

if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== output) {
  console.error("Wedding Project Motion dashboard preflight snapshot stale; run sync with --write");
  process.exit(1);
}

console.log(`Wedding Project Motion dashboard preflight current: Opening=${snapshot.opening.state} Profile=${snapshot.profile.state}`);
