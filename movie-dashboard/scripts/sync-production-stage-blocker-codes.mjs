import {execFileSync} from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const dashboardRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const repoRoot=path.resolve(dashboardRoot,"..");
const motionStudioRoot=path.join(repoRoot,"motion-studio");
const outputPath=path.join(dashboardRoot,"src/data/movieProductionStageBlockerCodes.generated.ts");
const allowedCode=/^[A-Z][A-Z0-9_]*(?::[A-Z0-9_.-]+)*$/;

const sources={
  opening:"scripts/opening-v1-production-status.mts",
  profile:"scripts/profile-v1-production-status.mts",
};

function readStatus(projectId,script){
  const report=JSON.parse(execFileSync(process.execPath,["--no-warnings",script,"--json"],{cwd:motionStudioRoot,encoding:"utf8"}));
  const expectedSchema=projectId==="opening"?"opening-v1-production-status/v1":"profile-v1-production-status/v1";
  if(report.schemaVersion!==expectedSchema||report.authority!=="DERIVED_PRODUCTION_STATUS")throw new Error(`${projectId}: unexpected production status contract ${report.schemaVersion}/${report.authority}`);
  const stages={};
  for(const [stageName,stage] of Object.entries(report.stages??{})){
    const codes=Array.isArray(stage?.blockerCodes)?stage.blockerCodes.map(String):[];
    if(new Set(codes).size!==codes.length)throw new Error(`${projectId}:${stageName}: duplicate blockerCodes`);
    for(const code of codes){
      if(!allowedCode.test(code)||code.includes("/")||code.includes("\\")||code.includes(" "))throw new Error(`${projectId}:${stageName}: unstable blocker code ${code}`);
    }
    if(codes.length>0)stages[stageName]=codes;
  }
  return stages;
}

const snapshot={
  schemaVersion:"wedding-movie-production-stage-blocker-codes/v1",
  authority:"MOTION_STUDIO_STABLE_STAGE_BLOCKER_CODES",
  source:{
    opening:"motion-studio/scripts/opening-v1-production-status.mts#stages.*.blockerCodes",
    profile:"motion-studio/scripts/profile-v1-production-status.mts#stages.*.blockerCodes",
  },
  projects:{
    opening:{stages:readStatus("opening",sources.opening)},
    profile:{stages:readStatus("profile",sources.profile)},
  },
  guardrails:[
    "RAW_BLOCKER_DETAIL != GENERATED_BLOCKER_CODE",
    "ABSOLUTE_PATH_MUST_NOT_ENTER_GENERATED_BLOCKER_CODES",
    "GENERATED_BLOCKER_CODE_VISIBLE != BLOCKER_RESOLVED",
  ],
};

const output=`// AUTO-GENERATED by scripts/sync-production-stage-blocker-codes.mjs\n// Stable codes only. Raw Motion Studio blocker details stay out of Dashboard snapshots.\n\nexport const movieProductionStageBlockerCodes = ${JSON.stringify(snapshot,null,2)} as const;\n`;
if(process.argv.includes("--write")){
  fs.writeFileSync(outputPath,output,"utf8");
  console.log(`Production stage blocker codes synced: opening=${Object.keys(snapshot.projects.opening.stages).length} stages, profile=${Object.keys(snapshot.projects.profile.stages).length} stages`);
  process.exit(0);
}
if(!fs.existsSync(outputPath)){console.error("Production stage blocker code snapshot missing. Run: node scripts/sync-production-stage-blocker-codes.mjs --write");process.exit(1)}
if(fs.readFileSync(outputPath,"utf8")!==output){console.error("Production stage blocker code snapshot is stale. Run: node scripts/sync-production-stage-blocker-codes.mjs --write");process.exit(1)}
console.log(`Production stage blocker code snapshot current: opening=${Object.keys(snapshot.projects.opening.stages).length} stages, profile=${Object.keys(snapshot.projects.profile.stages).length} stages`);
